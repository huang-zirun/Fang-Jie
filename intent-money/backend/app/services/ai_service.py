# 使用历史记录（简单的内存缓存）
_fallback_usage_history = []

def _select_fallback(
    intent_name: str,
    platform_name: str,
    fallback_pool: list[dict] | None = None
) -> dict:
    """智能选择fallback内容.
    
    策略：
    1. 根据意图和平台过滤候选fallback
    2. 优先选择最近未使用的fallback
    3. 记录使用历史
    
    Args:
        intent_name: 意图名称（如"引流拿客户"、"成交赚钱"等）
        platform_name: 平台名称（如"抖音"、"小红书"等）
        fallback_pool: fallback池，默认使用FALLBACK_POOL
    
    Returns:
        选中的fallback内容（副本）
    """
    import random
    
    if fallback_pool is None:
        fallback_pool = FALLBACK_POOL
    
    # 如果fallback池为空，使用SAFE_FALLBACK_CONTENT
    if not fallback_pool:
        return SAFE_FALLBACK_CONTENT.copy()
    
    # 过滤候选fallback
    candidates = []
    for fb in fallback_pool:
        # 匹配意图
        fb_tags = fb.get("tags", [])
        intent_match = any(tag in intent_name for tag in fb_tags) if fb_tags else False
        
        # 匹配平台
        fb_platforms = fb.get("platforms", [])
        platform_match = any(platform in platform_name for platform in fb_platforms) if fb_platforms else False
        
        # 如果有匹配的意图或平台，加入候选
        if intent_match or platform_match:
            candidates.append(fb)
    
    # 如果没有匹配的，使用全部fallback
    if not candidates:
        candidates = fallback_pool
    
    # 优先选择最近未使用的fallback
    for fb in candidates:
        # 检查是否在最近10次使用过
        if fb not in _fallback_usage_history[-10:]:
            _fallback_usage_history.append(fb)
            # 保持历史记录在合理范围
            if len(_fallback_usage_history) > 100:
                _fallback_usage_history.pop(0)
            return fb.copy()
    
    # 如果所有fallback都最近用过，随机选择一个
